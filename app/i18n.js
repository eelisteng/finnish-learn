  FI.I18N = { zh: ZH, en: EN }

  const escapeHtml = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  }[c]))
  function lookup(lang, key) {
    const table = FI.I18N[lang] || ZH
    return table[key] ?? ZH[key] ?? key
  }
  function fill(text, vars, escape) {
    return String(text).replace(/\{\{(\w+)\}\}/g, (_, k) => {
      const v = vars?.[k] ?? ''
      return escape ? escapeHtml(v) : String(v)
    })
  }
  /** Plain text (toasts, comparisons). Interpolated values are NOT escaped. */
  FI.tr = (lang, key, vars) => fill(lookup(lang, key), vars, false)
  /** HTML-safe: interpolated values are escaped; markup lives in the dictionary. */
  FI.trHtml = (lang, key, vars) => fill(lookup(lang, key), vars, true)

