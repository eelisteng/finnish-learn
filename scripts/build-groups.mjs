/**
 * Slices the content pack into fixed-size learning groups (5 items each),
 * one lane for words and one for sentences, per CEFR level. Emits:
 *   data/groups.json   - versioned, build-time reviewed group index
 *   app/data.js        - classic-script bundle so the app also works from file://
 *
 *   node scripts/build-groups.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { GROUP_TITLES, GROUP_TITLES_EN } from '../data/content-source.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pack = JSON.parse(readFileSync(join(root, 'data', 'packs', 'a1-core.json'), 'utf8'))
const topicsPath = join(root, 'data', 'topics.json')
const topics = existsSync(topicsPath)
  ? JSON.parse(readFileSync(topicsPath, 'utf8')).topics : {}
const GROUP_SIZE = 5

/**
 * The workbook adds ~190 groups, far too many to name by hand. Name each new
 * group after the topic shared by most of its words (the workbook is organised
 * by topic, so chunks are usually homogeneous). Reviewed demo groups keep
 * their hand-authored bilingual titles.
 */
function groupTitle(id, level, kind, index, itemIds, wordById) {
  if (GROUP_TITLES[id]) {
    return { title: GROUP_TITLES[id], titleEn: GROUP_TITLES_EN[id] ?? null }
  }
  if (kind === 'sentence') {
    return {
      title: `${level} 句子 · 第 ${index} 组`,
      titleEn: `${level} sentences · ${index}`,
    }
  }
  const counts = new Map()
  for (const id2 of itemIds) {
    const t = wordById.get(id2)?.topicId
    if (t) counts.set(t, (counts.get(t) ?? 0) + 1)
  }
  const dominant = [...counts.entries()].sort((a, b) => b[1] - a[1])[0]?.[0]
  const info = topics[dominant] ?? { zh: '综合', en: 'Mixed topics' }
  return {
    title: `${info.zh} · ${level} 第 ${index} 组`,
    titleEn: `${info.en} · ${level} ${index}`,
  }
}

function chunk(items, size) {
  const out = []
  for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size))
  return out
}

const groups = []
const levels = []
const wordById = new Map(pack.words.map((w) => [w.id, w]))

for (const level of pack.levels) {
  const words = pack.words.filter((w) => w.cefr === level).map((w) => w.id)
  const sentences = pack.sentences.filter((s) => s.cefr === level).map((s) => s.id)

  for (const [kind, ids] of [['word', words], ['sentence', sentences]]) {
    const letter = kind === 'word' ? 'W' : 'S'
    chunk(ids, GROUP_SIZE).forEach((itemIds, i) => {
      const id = `${level}-${letter}-${String(i + 1).padStart(2, '0')}`
      const names = groupTitle(id, level, kind, i + 1, itemIds, wordById)
      groups.push({
        id,
        level,
        kind,
        index: i + 1,
        size: itemIds.length,
        partial: itemIds.length < GROUP_SIZE,
        title: names.title,
        ...(names.titleEn ? { titleEn: names.titleEn } : {}),
        itemIds,
      })
    })
  }

  levels.push({
    level,
    wordCount: words.length,
    sentenceCount: sentences.length,
    wordGroups: Math.ceil(words.length / GROUP_SIZE),
    sentenceGroups: Math.ceil(sentences.length / GROUP_SIZE),
    sentenceStatus: sentences.length >= GROUP_SIZE ? 'ready' : 'pending',
  })
}

const groupIndex = {
  format: 'finnish-learn-groups',
  schema: 1,
  contentVersion: pack.version,
  groupSize: GROUP_SIZE,
  levels,
  groups,
}

writeFileSync(join(root, 'data', 'groups.json'), `${JSON.stringify(groupIndex, null, 2)}\n`, 'utf8')

mkdirSync(join(root, 'app'), { recursive: true })
writeFileSync(
  join(root, 'app', 'data.js'),
  `/* Generated by scripts/build-groups.mjs - do not edit by hand. */\n` +
  `window.FI_DATA = ${JSON.stringify({ pack, groups: groupIndex })};\n`,
  'utf8',
)

console.log(`Built data/groups.json + app/data.js`)
console.log(`  ${groups.length} groups (${groups.filter((g) => g.kind === 'word').length} word / ${groups.filter((g) => g.kind === 'sentence').length} sentence)`)
for (const l of levels) {
  console.log(`  ${l.level}: ${l.wordGroups} word group(s) / ${l.sentenceGroups} sentence group(s), sentences ${l.sentenceStatus}`)
}
const partial = groups.filter((g) => g.partial)
if (partial.length) console.log(`  WARN partial groups: ${partial.map((g) => `${g.id}(${g.size})`).join(', ')}`)
